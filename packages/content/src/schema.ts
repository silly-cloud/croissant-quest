import { z } from "zod";

export const QuestionKind = z.enum(["choice", "type", "en2fr", "build", "fix", "fr2en"]);
export type QuestionKind = z.infer<typeof QuestionKind>;

/** Pronunciation triple: English phonetic, Gujarati, Devanagari. */
export const Pron = z.object({ e: z.string(), g: z.string(), h: z.string() });
export type Pron = z.infer<typeof Pron>;

export const Question = z
  .object({
    t: z.number().int().min(1), // topic id
    tier: z.number().int().min(1).max(5),
    k: QuestionKind,
    tag: z.string().min(1),
    a: z.string().min(1), // answer
    s: z.string().optional(), // sentence (may contain ___)
    en: z.string().optional(), // English gloss / prompt
    o: z.array(z.string()).optional(), // options (choice, fr2en)
    bad: z.string().optional(), // fix: the wrong sentence
    alt: z.array(z.string()).optional(), // other accepted answers (en2fr)
    why: z.tuple([z.string(), z.string()]).optional(), // [rule, trick] for exception questions
    _ai: z.boolean().optional(), // generated by the coach, not in the bank
    pr: Pron.optional(),
  })
  .superRefine((q, ctx) => {
    const need = (ok: boolean, msg: string) => ok || ctx.addIssue({ code: "custom", message: msg });
    if (q.k === "choice") {
      need(!!q.s && q.s.includes("___"), "choice needs s with ___");
      need(!!q.o && q.o.includes(q.a), "choice options must include the answer");
    }
    if (q.k === "fr2en") need(!!q.s && !!q.o && q.o.includes(q.a), "fr2en needs s and options containing a");
    if (q.k === "type") need(!!q.s && q.s.includes("___"), "type needs s with ___");
    if (q.k === "en2fr" || q.k === "build") need(!!q.en, `${q.k} needs en`);
    if (q.k === "fix") need(!!q.s && !!q.bad, "fix needs s and bad");
  });
export type Question = z.infer<typeof Question>;

/** Stable identity of a question; saved progress is keyed on this. Do not change the format. */
export function qid(q: Pick<Question, "t" | "k" | "s" | "en" | "a">): string {
  return q.t + "|" + q.k + "|" + (q.s || q.en || "") + "|" + q.a;
}

export const Topic = z.tuple([z.number().int(), z.string()]);
export type Topic = z.infer<typeof Topic>;
